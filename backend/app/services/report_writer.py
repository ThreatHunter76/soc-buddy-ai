def generate_report(
    detections,
    mitre_results,
    iocs,
    risk
):

    report = {}

    # ==========================
    # Executive Summary
    # ==========================

    security_detections = [

        d.get("name")

        for d in detections

        if d.get("severity") != "INFO"

    ]


    informational_observations = [

        d.get("name")

        for d in detections

        if d.get("severity") == "INFO"

    ]


    detection_names = security_detections.copy()


    report["executive_summary"] = (

        "Security analysis identified: "

        + ", ".join(security_detections)

        if security_detections

        else "No security threats were identified."

    )


    if informational_observations:

        report["informational_observations"] = (
            informational_observations
        )

    # ==========================
    # Threat Summary
    # ==========================

    security_events = [

        d for d in detections

        if d.get("severity") != "INFO"

    ]


    observations = [

        d for d in detections

        if d.get("severity") == "INFO"

    ]


    report["threat_summary"] = (

        f"{len(security_events)} security events "

        "were detected requiring review. "

        f"{len(observations)} informational observations "

        "were recorded."

    )


    # ==========================
    # Risk Assessment
    # ==========================

    report["risk_level"] = risk.get(
        "risk_level",
        "UNKNOWN"
    )


    report["confidence"] = risk.get(
        "confidence",
        0
    )


    # ==========================
    # MITRE ATT&CK
    # ==========================

    report["mitre_attack"] = mitre_results


    # ==========================
    # Indicators of Compromise
    # ==========================

    report["indicators"] = iocs


    # ==========================
    # Evidence
    # ==========================

    evidence = detection_names.copy()


    network_detection = next(
        (
            d for d in detections
            if d.get("category") == "Network Activity"
        ),
        None
    )


    if network_detection:

        network_evidence = {

            "source_ip": network_detection.get(
                "source_ip"
            ),

            "destination_ip": network_detection.get(
                "destination_ip"
            ),

            "destination_port": network_detection.get(
                "destination_port"
            ),

            "protocol": network_detection.get(
                "protocol"
            ),

            "bytes": network_detection.get(
                "bytes"
            )

        }

        evidence.append(network_evidence)


    report["evidence"] = evidence


    # ==========================
    # Recommended Actions
    # ==========================

    recommendations = []


    for detection in detections:

        name = detection.get(
            "name",
            ""
        )


        if "PowerShell" in name:

            recommendations.append(
                "Review PowerShell activity and command history."
            )


        if "Login" in name:

            recommendations.append(
                "Investigate account authentication activity."
            )


        if "Network" in name:

            recommendations.append(
                "Review network traffic and firewall logs."
            )


    report["recommended_actions"] = list(
        set(recommendations)
    )


    # ==========================
    # Analyst Notes
    # ==========================

    report["analyst_notes"] = (
        "Analysis generated by SOC Buddy AI detection engine."
    )


    return report